"""Generate the C0 wire declarations from the frozen contract, without dependencies.

Run python3 internal/nativecontract/generate.py [--check]. The OpenAPI area is
authored here; the shared bundle still uses node api/generate.mjs --write.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPEC = json.loads((Path(__file__).with_name("contract.json")).read_text())
SCHEMAS = SPEC["schemas"]
LICENSE = "SPDX-License-Identifier: AGPL-3.0-only"


def go_name(name):
    return name if name == "NativeFinalReceipt" else name.removeprefix("Native")


def title(name):
    acronyms = {"id": "ID", "url": "URL", "json": "JSON", "pty": "PTY", "pid": "PID", "utf8": "UTF8", "ms": "MS", "ttl": "TTL"}
    return "".join(acronyms.get(word, word.capitalize()) for word in name.split("_"))


def go_type(schema):
    if "$ref" in schema:
        return go_name(schema["$ref"].split("/")[-1])
    if "anyOf" in schema:
        nonnull = [item for item in schema["anyOf"] if item.get("type") != "null"]
        if len(nonnull) == 1 and len(nonnull) != len(schema["anyOf"]):
            return "*" + go_type(nonnull[0])
    if "oneOf" in schema or "anyOf" in schema:
        return "json.RawMessage"
    kind = schema["type"]
    if kind == "array":
        return "[]" + go_type(schema["items"])
    if schema.get("format") == "date-time":
        return "time.Time"
    return {"string": "string", "integer": "int64", "number": "float64", "boolean": "bool"}[kind]


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(ts_type(item) for item in schema[union])
    kind = schema["type"]
    if kind == "array":
        return "Array<" + ts_type(schema["items"]) + ">"
    if kind == "object":
        return "{ " + "; ".join(key + ": " + ts_type(value) for key, value in schema["properties"].items()) + " }"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}[kind]


def dto_go():
    out = [f"// {LICENSE}", "// Code generated by nativecontract/generate.py; DO NOT EDIT.", "", "package nativecontract", "", 'import ("encoding/json"; "time")', ""]
    for name, schema in SCHEMAS.items():
        out += [f"// {go_name(name)} is the {name} wire schema. Validate before use."]
        if schema.get("type") == "object":
            out += [f"type {go_name(name)} struct {{"]
            for key, prop in schema["properties"].items():
                out += [f'\t{title(key)} {go_type(prop)} `json:"{key}"`']
            out += ["}", ""]
        elif name == "NativeLocalEnvelope":
            out += ['type LocalEnvelope struct {', 'Protocol string `json:"protocol"`', 'RequestID string `json:"request_id"`', 'Method string `json:"method"`', 'ExpectedBinding *Binding `json:"expected_binding"`', 'Params json.RawMessage `json:"params"`', '}', ""]
        elif name == "NativeDaemonCommand":
            out += ['type DaemonCommand struct {', 'Kind string `json:"kind"`', 'Params json.RawMessage `json:"params"`', '}', ""]
        else:
            out += [f"type {go_name(name)} {go_type(schema)}", "const ("]
            for value in schema.get("enum", []):
                out += [f'{go_name(name)}{title(value)} {go_name(name)} = {json.dumps(value)}']
            out += [")", ""]
    return "\n".join(out)


def dto_ts():
    out = [f"// {LICENSE}", "// Code generated by nativecontract/generate.py; DO NOT EDIT.", "// UUIDs/dates are strings; sequence/seq stay decimal strings to preserve uint64.", "export const nativeSessionContract = 'native-session/1.0' as const", "export const nativeSessionProtocol = 'aeon-native-session/1' as const", ""]
    for name, schema in SCHEMAS.items():
        if name == "NativeStreamEvent":
            props = schema["properties"]
            common = "; ".join(k + ": " + ts_type(v) for k, v in props.items() if k not in ("kind", "payload"))
            arms = ["{ kind: " + json.dumps(kind) + "; payload: " + target + " }" for kind, target in SPEC["stream_rules"]["kind_payload_map"].items()]
            out += [f"export type {name} = {{ {common} }} & (", "  " + "\n  | ".join(arms), ")", ""]
        else:
            out += [f"export type {name} = {ts_type(schema)}", ""]
    out += ["export const nativeSessionBounds = " + json.dumps(SPEC["bounds"], indent=2) + " as const", "", "export const nativeSessionPayloadSchemas = " + json.dumps(SPEC["stream_rules"]["kind_payload_map"], indent=2) + " as const", ""]
    return "\n".join(out)


def routes_go():
    out = [f"// {LICENSE}", "// Code generated by nativecontract/generate.py; DO NOT EDIT.", "package nativecontract", "", "const (", 'ContractVersion = "native-session/1.0"', 'LocalProtocol = "aeon-native-session/1"', 'LocalProtocolHeader = "X-Aeon-Session-Protocol"', 'ViewerHeader = "X-Aeon-Viewer-ID"', 'ControlHeader = "X-Aeon-Attach-Capability"']
    for name, value in SPEC["bounds"].items():
        out += [f"{title(name)} = {value}"]
    out += [")", "", "// Route declares a wire surface; paths never convey authority.", "type Route struct { Method, Path, OperationID, RequestSchema, ResponseSchema, Authority string }", "", "func PublicRoutes() []Route { return []Route{"]
    for route in SPEC["openapi_routes"]:
        fields = [route["method"], route["path"], route["operation_id"], route["request_schema"] or "", route["response_schema"], route["authorization"]]
        out += ["{" + ",".join(json.dumps(v) for v in fields) + "},"]
    out += ["} }", "", "func LocalRoutes() []Route { return []Route{"]
    for route in SPEC["local_messages"]:
        fields = [route["http_method"], route["path"], route["name"], route["params_schema"], route["response_schema"], route["authorization"]]
        out += ["{" + ",".join(json.dumps(v) for v in fields) + "},"]
    out += ["} }", "", "func StreamPayloadSchemas() map[string]string { return map[string]string{"]
    for kind, schema in SPEC["stream_rules"]["kind_payload_map"].items():
        out += [json.dumps(kind) + ":" + json.dumps(schema) + ","]
    out += ["} }", ""]
    return "\n".join(out)


def yaml(value, depth):
    """Block keys and JSON flow values preserve quoted prose without YAML aliases."""
    prefix = " " * depth
    if not isinstance(value, dict):
        raise ValueError("expected a block mapping")
    lines = []
    for key, item in value.items():
        key = json.dumps(key) if re.search(r"[:\s]", key) or key.isdigit() else key
        if isinstance(item, dict) and item:
            lines += [prefix + key + ":", yaml(item, depth + 2)]
        else:
            lines += [prefix + key + ": " + json.dumps(item, ensure_ascii=True)]
    return "\n".join(lines)


def parameter(name, schema, location="query", required=False, description=None):
    result = {"name": name, "in": location, "required": required, "schema": schema}
    if description:
        result["description"] = description
    return result


def area():
    paths = {}
    for route in SPEC["openapi_routes"]:
        path = route["path"].removeprefix("/api")
        item = paths.setdefault(path, {})
        if "parameters" not in item:
            ids = re.findall(r"\{([^}]+)\}", path)
            if ids:
                item["parameters"] = [parameter(name, {"type": "string", "format": "uuid"}, "path", True) for name in ids]
        method = route["method"].lower()
        operation = {"operationId": route["operation_id"], "description": "C0 mounts an authenticated disabled handler returning feature_disabled/503 with zero database or native side effects. Enabled behavior is reserved for qualified I1/I2 wiring. Authority: " + route["authorization"], "security": [{"agentKey": []}, {"session": []}]}
        params = []
        if path.endswith("/stream"):
            operation["description"] += " Fetch-SSE sends X-Aeon-Viewer-ID and authenticated proof, never a token URL. Last-Event-ID is <generation>:<seq>; seq is gapless per generation. PTY is server-side 403 for agents and read-only for people. Each frame/keepalive rechecks access; transcript source is unavailable in v1."
            params += [parameter("view", {"type": "string", "enum": ["structured", "expert", "terminal"], "default": "structured"}), parameter("after", {"type": "string", "maxLength": 512}), parameter("Last-Event-ID", {"type": "string", "maxLength": 64, "pattern": "^(0|[1-9][0-9]{0,15}):(0|[1-9][0-9]{0,19})$"}, "header"), parameter("X-Aeon-Viewer-ID", {"type": "string", "format": "uuid"}, "header", True)]
            for name, schema in (("expected_runtime_epoch", {"type": "string", "format": "uuid"}), ("expected_binding_revision", {"type": "integer", "minimum": 0, "maximum": 9007199254740991}), ("expected_harness_session_id", {"type": "string", "format": "uuid"})):
                params += [parameter(name, schema, required=True)]
        elif path.endswith("/events"):
            params += [parameter("before", {"type": "string", "pattern": "^(0|[1-9][0-9]{0,19})$"}), parameter("limit", {"type": "integer", "minimum": 1, "maximum": 500, "default": 200}), parameter("generation", {"type": "integer", "minimum": 0, "maximum": 9007199254740991}, required=True)]
            operation["description"] += " Replay is exclusive before sequence in one current generation, newest first, at most 500 items and 1 MiB. Retention/gaps are explicit; raw Expert/PTY content is never durable."
        elif path.endswith("/receipts") or path.endswith("/commands"):
            maximum = 50 if path.endswith("/commands") else 100
            params += [parameter("after", {"type": "string", "maxLength": 512}), parameter("limit", {"type": "integer", "minimum": 1, "maximum": maximum, "default": 25})]
        if route["request_schema"] in ("NativeInput", "NativeInterrupt", "NativeStop", "NativeTakeIntent", "NativeReturnIntent", "NativeApprovalDecision", "NativeEndControl"):
            params += [parameter("X-Aeon-Attach-Capability", {"type": "string", "minLength": 1, "maxLength": 4096}, "header", route["request_schema"] != "NativeEndControl")]
        if params:
            operation["parameters"] = params
        if route["request_schema"] and route["request_schema"] != "query":
            operation["requestBody"] = {"required": True, "content": {"application/json": {"schema": {"$ref": "#/components/schemas/" + route["request_schema"]}}}}
        stream = route["response_schema"].endswith(" SSE")
        response_schema = route["response_schema"].removesuffix(" SSE")
        headers = {"Aeon-Contract": {"$ref": "#/components/headers/NativeSessionContract"}, "Cache-Control": {"schema": {"type": "string", "enum": ["no-store"]}}}
        result = {"description": "Reserved qualified response; C0 returns 503. Acceptance is never delivery or exit evidence.", "headers": headers, "content": {"text/event-stream" if stream else "application/json": {"schema": {"$ref": "#/components/schemas/" + response_schema}}}}
        responses = {"200": result}
        if method == "post" and route["response_schema"] != "NativeFinalReceipt":
            responses["202"] = result
        for status, meaning in SPEC["http_status"].items():
            if status not in ("200", "202"):
                responses[status] = {"description": meaning + ("; C0 reason is feature_disabled, retryable false." if status == "503" else "."), "headers": headers, "content": {"application/json": {"schema": {"$ref": "#/components/schemas/NativeError"}}}}
        operation["responses"] = responses
        item[method] = operation
    components = {"headers": {"NativeSessionContract": {"description": "Owned native session wire contract, independent of the product release.", "schema": {"type": "string", "enum": ["native-session/1.0"]}}}, "schemas": SCHEMAS}
    return f"# {LICENSE}\n# aeon:owner internal/nativesessions\n# C0 frozen plan schemas plus LEAD c0-inputs refinements; generated by internal/nativecontract/generate.py.\n" + yaml({"paths": paths, "components": components}, 0) + "\n"


def main():
    if sys.argv[1:] not in ([], ["--check"]):
        raise SystemExit("Usage: python3 internal/nativecontract/generate.py [--check]")
    outputs = {"internal/nativecontract/dto.go": dto_go(), "internal/nativecontract/routes.go": routes_go(), "web/src/lib/nativeSessionContract.ts": dto_ts(), "api/areas/native-sessions.yaml": area()}
    # gofmt is a formatter, never a build or suite. It must use the approved toolchain.
    import subprocess
    for path, content in outputs.items():
        if path.endswith(".go"):
            content = subprocess.run(["gofmt"], input=content, capture_output=True, text=True, check=True).stdout
        destination = ROOT / path
        if "--check" in sys.argv:
            if not destination.exists() or destination.read_text() != content:
                raise SystemExit("Contract drift: " + path)
        else:
            destination.write_text(content)
    print("Native contract declarations match" if "--check" in sys.argv else "Generated native contract Go, TypeScript and OpenAPI area")


if __name__ == "__main__":
    main()
